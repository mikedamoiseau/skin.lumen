"""Generate skin.lumen/xml/Includes_LumenFilters.xml: the actions of the Genre / Decade picker (Custom_1117).

A pick reopens the grid at a new path: Kodi's genre node (videodb://movies/genres/5/) or titles/, plus a decade as a
smart playlist rule in the URL (?xsp=, URL-encoded JSON). The skin can't encode text, so every decade's rule is
written out here, for films and for shows. Run: python3 tools/build_filters.py
"""
import json
import os
import urllib.parse

# label, first year, last year ("Before 1950" starts at 1: films without a year have 0)
DECADES = [(f"{y}s", y, y + 9) for y in range(2020, 1949, -10)] + [("Before 1950", 1, 1949)]
TYPES = ["movies", "tvshows"]
SHOWS = "Container.Content(tvshows)"
ON = {"movies": f"!{SHOWS}", "tvshows": SHOWS}
FPATH = "$INFO[Window(home).Property(lumen.fpath)]"
DECADE_ON = "$EXP[LumenDecadeOn]"
GENRE_ON = "$EXP[LumenGenreOn]"


def xsp(kind, first=None, last=None):
    """The decade's rule; without one, an empty rule set (every title). A path with no options would be ignored when
    the grid is already at that path plus options: Kodi's ActivateWindow skips a path the current one starts with
    (CGUIMediaWindow::IsSameStartFolder)."""
    rules = [{"field": "year", "operator": "between", "value": [str(first), str(last)]}] if first else []
    rule = {"rules": {"and": rules}, "type": kind}
    return "?xsp=" + urllib.parse.quote(json.dumps(rule, separators=(",", ":")), safe="")


def is_decade(label):
    return f"String.IsEqual(Window(home).Property(lumen.fdecade),{label})"


def click(action, condition=None, indent="\t\t"):
    c = f' condition="{condition}"' if condition else ""
    return f"{indent}<onclick{c}>{action}</onclick>"


def go(indent="\t\t"):
    """Close the picker at once (Kodi won't change window under a modal dialog), then open the path the pick put in
    lumen.fpath as the window's start folder ("return" with "replace", GUIMediaWindow.cpp), so Back still goes Home."""
    return [click("Dialog.Close(1117,true)", indent=indent),
            click(f"ActivateWindow(videos,{FPATH},return,replace)", indent=indent)]


def set_path(base, decade=None, condition=None, indent="\t\t"):
    """lumen.fpath = base + the decade's rule, for films and for shows."""
    out = []
    for kind in TYPES:
        b = base(kind) if callable(base) else base
        tail = xsp(kind, *decade[1:]) if decade else xsp(kind)
        cond = " + ".join(c for c in (ON[kind], condition) if c)
        out.append(click(f"SetProperty(lumen.fpath,{b}{tail},home)", cond, indent))
    return out


def titles(kind):
    return f"videodb://{kind}/titles/"


def genre_actions():
    """List 11 (Kodi's genres): the genre picked, with the decade already chosen if there is one."""
    L = [click("SetProperty(lumen.fgenre,$INFO[ListItem.FolderPath],home)"),
         click("SetProperty(lumen.fgenrename,$ESCINFO[ListItem.Label],home)"),
         click("ClearProperty(lumen.fdecade,home)", f"!{DECADE_ON}")]
    for d in DECADES:
        L += set_path("$INFO[ListItem.FolderPath]", d, f"{DECADE_ON} + {is_decade(d[0])}")
    L += set_path("$INFO[ListItem.FolderPath]", None, f"!{DECADE_ON}")
    return L + go()


def all_genres_actions():
    """Button 10: no genre; the decade stays."""
    L = [click("ClearProperty(lumen.fgenre,home)"), click("ClearProperty(lumen.fgenrename,home)"),
         click("ClearProperty(lumen.fdecade,home)", f"!{DECADE_ON}")]
    for d in DECADES:
        L += set_path(titles, d, f"{DECADE_ON} + {is_decade(d[0])}")
    L += set_path(titles, None, f"!{DECADE_ON}")
    return L + go()


def decade_items():
    """List 12's items: All decades, then each decade; the genre stays."""
    I = "\t\t\t"
    genre = "$INFO[Window(home).Property(lumen.fgenre)]"
    items = []
    for d in [None] + DECADES:
        label = d[0] if d else "All decades"
        L = [f"\t\t<item>", f"{I}<label>{label}</label>"]
        if not d:
            L.append(f"{I}<property name=\"all\">1</property>")
        L.append(click(f"SetProperty(lumen.fdecade,{label},home)" if d else "ClearProperty(lumen.fdecade,home)", indent=I))
        L += set_path(genre, d, GENRE_ON, I)
        L += set_path(titles, d, f"!{GENRE_ON}", I)
        L.append(click("ClearProperty(lumen.fgenre,home)", f"!{GENRE_ON}", I))
        L += go(I)
        L.append("\t\t</item>")
        items += L
    return items


def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "skin.lumen", "xml", "Includes_LumenFilters.xml")
    X = ['<?xml version="1.0" encoding="UTF-8"?>',
         "<!-- GENERATED by tools/build_filters.py — edit the generator, not this file. -->",
         "<includes>",
         "\t<include name=\"LumenGenrePickActions\">", *genre_actions(), "\t</include>",
         "\t<include name=\"LumenAllGenresActions\">", *all_genres_actions(), "\t</include>",
         "\t<include name=\"LumenDecadeItems\">", *decade_items(), "\t</include>",
         "</includes>", ""]
    with open(out, "w") as f:
        f.write("\n".join(X))
    print(f"wrote {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
